-- Rotina para corrigir versao de pessoa, o max é 99, passando disto gera erro na rotina do ecommerce

CREATE TABLE NAGT_BKP_GEPESSOAVERSAO AS
SELECT * FROM GE_PESSOAVERSAO X WHERE ROWNUM = 1

TRUNCATE TABLE NAGT_BKP_GEPESSOAVERSAO;

BEGIN
  
  FOR cliente IN (SELECT SEQPESSOA FROM GE_PESSOA X WHERE VERSAO IN (0,99) AND EXISTS (SELECT 1 FROM GE_PESSOAVERSAO V WHERE V.SEQPESSOA = X.SEQPESSOA HAVING COUNT(1) >= 99))
   LOOP
     
     INSERT INTO NAGT_BKP_GEPESSOAVERSAO SELECT * FROM GE_PESSOAVERSAO V WHERE V.SEQPESSOA = cliente.SEQPESSOA;
     UPDATE GE_PESSOA X SET VERSAO = 0 WHERE X.SEQPESSOA = cliente.SEQPESSOA;
     DELETE FROM GE_PESSOAVERSAO X WHERE X.SEQPESSOA = cliente.SEQPESSOA;
     
     COMMIT;
   END LOOP;
   
 END;
 
